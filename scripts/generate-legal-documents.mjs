#!/usr/bin/env node
/**
 * Generates typed legal documents from the approved Markdown sources.
 *
 * Usage:
 *   node scripts/generate-legal-documents.mjs <path-to-docs/block/updated>
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const outputDir = resolve(here, '..', 'src', 'features', 'legal', 'documents');
const VERSION = '2026-10-30';

const DOCUMENTS = [
  {
    slug: 'offer',
    source: 'publicnaia-oferta-dlia-saita-onlain-servis.md',
    exportName: 'offerDocument',
    title: 'Публичная оферта',
    anchors: {
      1: 'general',
      2: 'subject',
      3: 'pricing',
      4: 'payment',
      5: 'access',
      6: 'refund',
      7: 'rights',
      8: 'personal-data',
      9: 'liability',
      10: 'changes',
      11: 'requisites',
    },
    aliases: { 6: ['compensation'] },
  },
  {
    slug: 'terms',
    source: 'polzovatelskoe-soglasenie-dlia-onlain-servisa.md',
    exportName: 'termsDocument',
    title: 'Пользовательское соглашение',
    anchors: {
      4: 'registration',
      6: 'payment',
      7: 'personal-data',
      12: 'contacts',
    },
  },
  {
    slug: 'cookies',
    source: 'politika-obrabotki-failov-kuki-cookies.md',
    exportName: 'cookiesDocument',
    title: 'Политика обработки файлов cookie',
    anchors: {
      1: 'general',
      3: 'cookies',
      4: 'legal-basis',
      5: 'third-parties',
      7: 'contacts',
    },
  },
];

const METADATA_LINE = /^(г\.\s|\d{2}\.\d{2}\.\d{4}$)/i;

function parseMarkdown(markdown, config) {
  const lines = markdown.replace(/\r\n/g, '\n').split('\n');
  const blocks = [];
  let subtitle;
  let paragraph = [];
  let bullets = [];
  let seenSection = false;

  const flushParagraph = () => {
    if (paragraph.length) {
      blocks.push({ type: 'p', text: paragraph.join(' ').trim() });
      paragraph = [];
    }
  };
  const flushBullets = () => {
    if (bullets.length) {
      blocks.push({ type: 'ul', items: bullets });
      bullets = [];
    }
  };
  const flush = () => {
    flushParagraph();
    flushBullets();
  };

  for (const rawLine of lines) {
    const trimmed = rawLine.trim();
    if (!trimmed) {
      flush();
      continue;
    }
    if (trimmed.startsWith('# ')) {
      flush();
      continue;
    }
    if (trimmed.startsWith('## ')) {
      flush();
      const text = trimmed.slice(3).trim();
      const numbered = /^(\d+)\./.exec(text);
      if (!seenSection && !numbered) {
        subtitle = text;
        continue;
      }
      seenSection = true;
      const block = { type: 'h2', text };
      const id = numbered ? config.anchors?.[Number(numbered[1])] : undefined;
      if (id) block.id = id;
      const aliases = numbered ? config.aliases?.[Number(numbered[1])] : undefined;
      if (aliases?.length) block.aliases = aliases;
      blocks.push(block);
      continue;
    }
    if (trimmed.startsWith('### ')) {
      flush();
      blocks.push({ type: 'h3', text: trimmed.slice(4).trim() });
      continue;
    }
    if (!seenSection && METADATA_LINE.test(trimmed)) {
      continue;
    }
    if (trimmed.startsWith('- ')) {
      flushParagraph();
      bullets.push(trimmed.slice(2).trim());
      continue;
    }
    flushBullets();
    paragraph.push(trimmed);
  }

  flush();
  return { subtitle, blocks };
}

function serialize(document, exportName) {
  return `// Generated by scripts/generate-legal-documents.mjs. Do not edit by hand.
import type { LegalDocument } from '../types';

export const ${exportName}: LegalDocument = ${JSON.stringify(document, null, 2)};
`;
}

async function main() {
  const sourceDir = process.argv[2];
  if (!sourceDir) {
    console.error('Укажите каталог с Markdown-документами.');
    process.exit(1);
  }
  await mkdir(outputDir, { recursive: true });

  for (const config of DOCUMENTS) {
    const markdown = await readFile(join(resolve(sourceDir), config.source), 'utf8');
    const parsed = parseMarkdown(markdown, config);
    const document = {
      slug: config.slug,
      title: config.title,
      ...(parsed.subtitle ? { subtitle: parsed.subtitle } : {}),
      version: VERSION,
      updatedAt: VERSION,
      blocks: parsed.blocks,
    };
    const target = join(outputDir, `${config.slug}.ts`);
    await writeFile(target, serialize(document, config.exportName), 'utf8');
    console.log(`${config.slug}: ${document.blocks.length} blocks`);
  }
}

await main();
